"""Build a provenance-aware, synthetic Python documentation dataset.

This module does not train models and writes only beneath data/ml/final by
default. Claims are controlled templates grounded in the project's curated
Python documentation passages; they are not human annotations.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from datetime import datetime, timezone
import csv
import hashlib
import json
from pathlib import Path
import random
import re
from difflib import SequenceMatcher
from typing import Any

from codeguard.ml.dataset import DEFAULT_ML_DIR, LABELS, _corpus


PROJECT_ROOT = Path(__file__).resolve().parents[4]
PILOT_CSV = DEFAULT_ML_DIR / "claims.csv"
CORPUS_PATH = Path(__file__).resolve().parents[1] / "corpus" / "python_docs.json"
FINAL_DIR = DEFAULT_ML_DIR / "final"
SEED = 42
FIELDS = (
    "claim", "evidence", "label", "data_origin", "source", "source_url", "license",
    "topic", "fact_key", "evidence_chunk_id", "source_section", "source_record_id",
    "leakage_group", "label_reason", "question_context", "title",
)

# One atomic proposition per curated evidence passage. Opposite claims are
# generated by hand as controlled templates and stay in the same leakage group.
PAIRS: dict[str, tuple[str, str, str]] = {
    "list_mutability": ("Python lists are mutable.", "Python lists are immutable.", "collections and mutability"),
    "tuple_mutability": ("Python tuples are immutable.", "Python tuples are mutable.", "collections and mutability"),
    "dict_insertion_order": ("Python dictionaries preserve insertion order.", "Python dictionaries do not preserve insertion order.", "dictionaries"),
    "set_insertion_order": ("Python sets are unordered.", "Python sets preserve insertion order.", "sets"),
    "list_comprehension_new_list": ("A Python list comprehension produces a new list.", "A Python list comprehension modifies its input list in place.", "comprehensions"),
    "dict_get_missing_key": ("dict.get returns None by default when a key is missing.", "dict.get raises KeyError by default when a key is missing.", "dictionaries and exceptions"),
    "list_front_queue_performance": ("Inserting or popping at the front of a Python list shifts the remaining elements.", "Inserting or popping at the front of a Python list leaves the remaining elements in place.", "collections and performance"),
    "sorted_stability": ("Python's sorted function is stable.", "Python's sorted function is unstable.", "built-ins and sorting"),
    "function_definition_executes_body": ("Defining a Python function does not execute its body.", "Defining a Python function immediately executes its body.", "functions"),
    "for_else_after_break": ("A Python for-else suite does not run when the loop exits with break.", "A Python for-else suite runs when the loop exits with break.", "loops"),
    "unhandled_exception_propagates": ("An unhandled Python exception propagates to the caller.", "An unhandled Python exception is silently discarded before reaching the caller.", "exceptions"),
    "with_open_closes_file": ("A file opened with a with statement is closed when the block exits, including after an exception.", "A file opened with a with statement stays open after the block exits with an exception.", "file handling and exceptions"),
}


def _norm(text: str) -> str:
    return re.sub(r"\W+", " ", (text or "").casefold()).strip()


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _write_csv(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(records)


def _normalize_pilot(record: dict[str, str]) -> dict[str, Any]:
    fact_key = record.get("fact_key") or "pilot_insufficient_" + record["leakage_group"].replace(":", "_")
    topic = {
        "list_mutability": "collections and mutability", "tuple_mutability": "collections and mutability",
        "dict_insertion_order": "dictionaries", "set_insertion_order": "sets",
        "sorted_stability": "built-ins and sorting",
    }.get(fact_key, "pilot out-of-scope example")
    return {
        "claim": record["claim"], "evidence": record.get("evidence", ""), "label": record["label"],
        "data_origin": "synthetic", "source": record.get("source") or "No passage retrieved in pilot",
        "source_url": record.get("source_url", ""),
        "license": ("PSF License Version 2 (Python documentation); attribution/source link retained"
                    if record.get("source_url") else "CodeGuard-generated synthetic claim; no source passage included"),
        "topic": topic, "fact_key": fact_key,
        "evidence_chunk_id": (record.get("evidence_chunk_id", "").split("#", 1)[0]
                               or "none:" + (record.get("leakage_group") or fact_key)),
        "source_section": record.get("source_section", ""),
        "source_record_id": "codeguard-pilot:" + (record.get("leakage_group") or fact_key),
        "leakage_group": "evidence:" + (record.get("evidence_chunk_id", "").split("#", 1)[0]
                                           or record.get("leakage_group") or fact_key),
        "label_reason": "Preserved from the existing synthetic pilot; not a human annotation. " + record.get("label_reason", ""),
        "question_context": record.get("question_context", ""), "title": record.get("title") or "No retrieved passage",
    }


def _make_claims(corpus_path: Path) -> list[dict[str, Any]]:
    corpus = _corpus(corpus_path)
    by_key = {row["fact_key"]: row for row in corpus}
    records: list[dict[str, Any]] = []
    for key, (supported, contradicted, topic) in PAIRS.items():
        source = by_key[key]
        group = "evidence:" + source["doc_id"]
        for claim, label in ((supported, "SUPPORTED"), (contradicted, "CONTRADICTED")):
            records.append({
                "claim": claim, "evidence": source["text"], "label": label, "data_origin": "synthetic",
                "source": source["source"], "source_url": source["url"],
                "license": "PSF License Version 2 (Python documentation); attribution/source link retained",
                "topic": topic, "fact_key": key, "evidence_chunk_id": source["doc_id"],
                "source_section": source["section"], "source_record_id": "python-docs:" + source["doc_id"],
                "leakage_group": group,
                "label_reason": "Controlled synthetic claim checked against the exact curated Python documentation passage. Opposite claim is contradicted by that passage; no independent human annotation.",
                "question_context": "Classify the claim against the cited Python documentation passage.",
                "title": "Curated Python documentation passage",
            })
    return records


def _exact_deduplicate(records: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], int]:
    kept: list[dict[str, Any]] = []
    seen: dict[tuple[str, str], str] = {}
    removed = 0
    for row in records:
        key = (_norm(row["claim"]), _norm(row["evidence"]))
        old_label = seen.get(key)
        if old_label is not None:
            if old_label != row["label"]:
                raise ValueError(f"Conflicting exact claim/evidence labels: {row['claim']}")
            removed += 1
            continue
        seen[key] = row["label"]
        kept.append(row)
    return kept, removed


def _near_duplicates(records: list[dict[str, Any]], threshold: float = 0.90) -> list[dict[str, Any]]:
    pairs = []
    for i, left in enumerate(records):
        for j in range(i + 1, len(records)):
            right = records[j]
            score = SequenceMatcher(None, _norm(left["claim"]), _norm(right["claim"])).ratio()
            if score >= threshold:
                pairs.append({"left": i, "right": j, "claim_similarity": round(score, 4),
                              "same_leakage_group": left["leakage_group"] == right["leakage_group"]})
    return pairs


def _group_splits(records: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in records:
        groups[row["leakage_group"]].append(row)
    # Stable seeded group assignment, prioritizing broad class coverage and
    # approximate 70/15/15 row proportions without splitting source evidence.
    target = {"train": .70, "validation": .15, "test": .15}
    total = len(records)
    group_names = list(groups)
    best: dict[str, list[dict[str, Any]]] | None = None
    best_score = float("inf")
    # Randomized group assignment with a class-coverage constraint. This is
    # small-data split planning, not model training; retain the closest valid
    # 70/15/15 row proportions while keeping every evidence group intact.
    for trial in range(12000):
        rng = random.Random(SEED + trial)
        shuffled = group_names.copy()
        rng.shuffle(shuffled)
        candidate: dict[str, list[dict[str, Any]]] = {name: [] for name in target}
        assignment = rng.choices(list(target), weights=[70, 15, 15], k=len(shuffled))
        for group_name, split_name in zip(shuffled, assignment):
            candidate[split_name].extend(groups[group_name])
        if any(set(row["label"] for row in rows) != set(LABELS) for rows in candidate.values()):
            continue
        score = sum(abs(len(candidate[name]) / total - target[name]) for name in target)
        if score < best_score:
            best, best_score = candidate, score
    if best is None:
        raise ValueError("Could not make grouped splits with all three labels represented in each partition")
    for rows in best.values():
        rows.sort(key=lambda row: (row["leakage_group"], row["claim"]))
    return best


def _distribution(rows: list[dict[str, Any]], field: str) -> dict[str, int]:
    return dict(sorted(Counter(str(row.get(field, "")) or "[blank]" for row in rows).items()))


def build_final_dataset(output_dir: str | Path = FINAL_DIR, pilot_csv: str | Path = PILOT_CSV,
                        corpus_path: str | Path = CORPUS_PATH) -> dict[str, Any]:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    pilot = [_normalize_pilot(row) for row in _read_csv(Path(pilot_csv))]
    records, duplicates_removed = _exact_deduplicate(pilot + _make_claims(Path(corpus_path)))
    if not records:
        raise ValueError("Final dataset must not be empty")
    required = set(FIELDS)
    errors = []
    for idx, row in enumerate(records):
        for field in required:
            optional = {"evidence", "source_section", "question_context", "title"}
            if row["label"] == "INSUFFICIENT_EVIDENCE":
                optional.add("source_url")
            if row.get(field) is None or (not str(row[field]).strip() and field in required - optional):
                errors.append(f"record {idx}: missing {field}")
        if row["label"] not in LABELS:
            errors.append(f"record {idx}: invalid label {row['label']}")
        if row["data_origin"] not in {"synthetic", "public", "manually_verified"}:
            errors.append(f"record {idx}: invalid data origin")
        if not row["evidence"] and row["label"] != "INSUFFICIENT_EVIDENCE":
            errors.append(f"record {idx}: labeled claim has no evidence")
    if errors:
        raise ValueError("Dataset validation failed: " + "; ".join(errors[:10]))

    # Detect same normalized claim with contradictory labels even if evidence differs.
    claim_labels: dict[str, set[str]] = defaultdict(set)
    for row in records:
        claim_labels[_norm(row["claim"])].add(row["label"])
    conflicts = [claim for claim, labels in claim_labels.items() if len(labels) > 1]
    if conflicts:
        raise ValueError(f"Conflicting labels for normalized claims: {conflicts[:5]}")

    splits = _group_splits(records)
    group_sets = {name: {r["leakage_group"] for r in rows} for name, rows in splits.items()}
    if any(group_sets[a] & group_sets[b] for a, b in (("train", "validation"), ("train", "test"), ("validation", "test"))):
        raise ValueError("Leakage group crossed a split")
    near = _near_duplicates(records)
    for pair in near:
        left, right = records[pair["left"]], records[pair["right"]]
        if left["leakage_group"] != right["leakage_group"]:
            raise ValueError("Near duplicates are not kept in a common leakage group")

    _write_csv(output / "claims.csv", records)
    for name, rows in splits.items():
        _write_csv(output / f"{name}.csv", rows)
    corpus_bytes = Path(corpus_path).read_bytes()
    metadata = {
        "dataset_version": "2.0.0-python-docs-synthetic-20260926",
        "created_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "total_records": len(records), "records_per_class": _distribution(records, "label"),
        "records_per_source": _distribution(records, "source"), "records_per_topic": _distribution(records, "topic"),
        "data_origins": _distribution(records, "data_origin"), "licenses": sorted({r["license"] for r in records}),
        "source_urls": sorted({r["source_url"] for r in records if r["source_url"]}),
        "source_corpus_sha256": hashlib.sha256(corpus_bytes).hexdigest(),
        "source_corpus_records": len(_corpus(Path(corpus_path))),
        "duplicate_counts": {"exact_claim_evidence_removed": duplicates_removed},
        "near_duplicate_count": len(near), "conflicting_label_count": len(conflicts),
        "split_method": "Deterministic seed-42 group assignment by evidence chunk; grouped evidence/paired claims remain together. Approximate 70/15/15 is secondary to group integrity.",
        "split_sizes": {name: len(rows) for name, rows in splits.items()},
        "split_class_distribution": {name: _distribution(rows, "label") for name, rows in splits.items()},
        "feature_descriptions": {
            "claim": "Claim text generated from explicit, narrow Python documentation propositions.",
            "evidence": "Curated documentation passage associated with the claim; blank only where the existing pilot had no retrieved passage.",
            "label": "SUPPORT/CONTRADICT based on direct passage semantics; INSUFFICIENT_EVIDENCE means the supplied evidence does not establish the claim, not that the claim is false.",
            "topic": "Python topic associated with the source proposition.", "fact_key": "Stable proposition identifier.",
            "data_origin": "All examples are synthetic claim wording; source text/provenance is retained.",
        },
        "quality": {
            "missing_values": {field: sum(not str(r.get(field, "")).strip() for r in records) for field in FIELDS},
            "evidence_coverage": sum(bool(r["evidence"].strip()) for r in records),
            "duplicate_evidence_count": len(records) - len({(r["evidence_chunk_id"], r["evidence"]) for r in records}),
            "near_duplicate_pairs": near, "conflicting_labels": conflicts,
            "provenance_missing_source_url": sum(not r["source_url"] for r in records),
        },
        "limitations": [
            "All 31 records are synthetic claim wording, not independent expert or human annotations.",
            "No compatible public Python claim/evidence dataset was found and used; broad-domain fact-checking data were excluded for domain mismatch.",
            "The dataset is small and based on a 12-passage curated Python documentation corpus; it is not representative of real AI explanations.",
            "Contradictions are controlled polarity counterparts and may make labels lexically easy; labels reflect only the supplied passage.",
            "Insufficient-evidence examples mean the provided passage does not establish the claim; this does not imply the claim is false.",
            "Group integrity may produce split proportions differing from the nominal 70/15/15 target.",
        ],
    }
    analysis = {
        "overview": {"total_records": len(records), "class_distribution": metadata["records_per_class"],
                     "origin_distribution": metadata["data_origins"], "topic_distribution": metadata["records_per_topic"],
                     "source_distribution": metadata["records_per_source"]},
        "quality": metadata["quality"], "split_sizes": metadata["split_sizes"],
        "split_class_distribution": metadata["split_class_distribution"],
        "limitations": metadata["limitations"],
    }
    (output / "dataset_metadata.json").write_text(json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8")
    (output / "dataset_analysis.json").write_text(json.dumps(analysis, indent=2, ensure_ascii=False), encoding="utf-8")
    sources = {
        "used_sources": [{"name": "Python documentation passages curated in CodeGuard", "url": "https://docs.python.org/3/",
                          "license": "Python Software Foundation License Version 2", "records": sum(bool(r["source_url"]) for r in records),
                          "fields": list(FIELDS), "labels": list(LABELS), "relevance": "Primary Python semantics evidence; claim wording is synthetic.",
                          "limitations": "The repository's existing 12 short passages, not the complete Python documentation."}],
        "candidates": [
            {"name": "FEVER", "url": "https://fever.ai/dataset/fever.html", "license": "Wikipedia article terms or CC BY-SA 3.0 where terms unavailable (official notice)",
             "records": 185445, "fields": ["id", "label", "claim", "evidence"], "labels": ["SUPPORTS", "REFUTES", "NOT ENOUGH INFO"],
             "claim_present": True, "evidence_present": "Evidence sets for supported/refuted; NEI uses null evidence references.",
             "relevance": "General textual claim verification, but Wikipedia subject domain is unlike Python documentation.",
             "mapping": "Potential label mapping exists, but evidence must be dereferenced and converted; NEI placeholder is not evidence text.",
             "limitations": "Out-of-domain; Wikipedia-derived source/licensing obligations; excluded from final data."},
            {"name": "SciFact", "url": "https://github.com/allenai/scifact", "license": "Claims/evidence annotations CC BY 4.0; abstract corpus ODC-By 1.0",
             "records": "about 1.4K claims", "fields": ["id", "claim", "evidence", "cited_doc_ids"], "labels": ["SUPPORT", "CONTRADICT"],
             "claim_present": True, "evidence_present": "Sentence-indexed rationales in biomedical abstracts.",
             "relevance": "Claim/evidence shape is close, but biomedical subject matter is not Python semantics.",
             "mapping": "SUPPORT→SUPPORTED, CONTRADICT→CONTRADICTED; no reliable INSUFFICIENT_EVIDENCE class in the released labeled claims.",
             "limitations": "Different domain and label coverage; corpus text has a separate ODC-By license; excluded."},
        ],
        "used_public_datasets": [],
        "exclusion_policy": "No dataset was added solely for scale. Candidates must have relevant domain, usable claim plus evidence text, mappable labels, and clear source terms.",
    }
    (output / "dataset_sources.json").write_text(json.dumps(sources, indent=2, ensure_ascii=False), encoding="utf-8")
    _write_plot(output / "dataset_analysis.png", metadata)
    return {"records": records, "splits": splits, "metadata": metadata, "sources": sources, "analysis": analysis}


def _write_plot(path: Path, metadata: dict[str, Any]) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        # A dependency-free SVG fallback keeps the requested visual summary
        # available in minimal environments.
        labels = metadata["records_per_class"]
        topics = metadata["records_per_topic"]
        bars = []
        y = 32
        max_label = max(labels.values(), default=1) or 1
        for name, count in labels.items():
            width = int(220 * count / max_label)
            bars.append(f'<text x="12" y="{y + 15}">{name}</text><rect x="190" y="{y}" width="{width}" height="20" fill="#4e91d9"/><text x="{198 + width}" y="{y + 15}">{count}</text>')
            y += 30
        topic_svg = []
        y = 32
        max_topic = max(topics.values(), default=1) or 1
        for name, count in topics.items():
            width = int(220 * count / max_topic)
            topic_svg.append(f'<text x="420" y="{y + 15}">{name}</text><rect x="650" y="{y}" width="{width}" height="20" fill="#43a6a0"/><text x="{658 + width}" y="{y + 15}">{count}</text>')
            y += 30
        height = max(150, y + 20)
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="940" height="' + str(height) + '" viewBox="0 0 940 ' + str(height) + '">'
               '<rect width="100%" height="100%" fill="#fff"/><text x="12" y="22" font-weight="bold">Records by label</text>'
               + ''.join(bars) + '<text x="420" y="22" font-weight="bold">Records by topic</text>' + ''.join(topic_svg) + '</svg>')
        path.with_suffix(".svg").write_text(svg, encoding="utf-8")
        return
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    labels = list(metadata["records_per_class"])
    axes[0].bar(labels, [metadata["records_per_class"][key] for key in labels], color=["#43a6a0", "#df6d64", "#e3b341"])
    axes[0].set_title("Records by label")
    axes[0].tick_params(axis="x", labelrotation=25)
    topics = metadata["records_per_topic"]
    axes[1].barh(list(topics), list(topics.values()), color="#567bc1")
    axes[1].set_title("Records by topic")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)


